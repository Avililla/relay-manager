import { plural } from "./format"

const num = (n: number): string => new Intl.NumberFormat("es-ES").format(n)

/** A duration for people: "19 ms", "1,5 s", "60 s" (seconds from 1000 ms up, never "60.000 ms"), with a no-break space. */
export function durationText(ms: number): string {
  if (ms < 1000) return `${num(Math.round(ms))}\u00a0ms`
  return `${new Intl.NumberFormat("es-ES", { maximumFractionDigits: 1 }).format(ms / 1000)}\u00a0s`
}

